// CuratedStockList returns the full curated stock list with sector classification.
func CuratedStockList() []modelStockInfo {
	var result []modelStockInfo
	seen := make(map[string]bool)
	for _, sector := range TargetSectors {
		codes := SectorStockMap[sector]
		for _, code := range codes {
			if seen[code] {
				continue
			}
			seen[code] = true
			info, ok := SectorStockInfo[code]
			name := ""
			exchange := "sz"
			if ok {
				name = info[0]
				exchange = info[1]
			}
			result = append(result, modelStockInfo{
				Code:     code,
				Name:     name,
				Exchange: exchange,
				Sector:   sector,
			})
		}
	}
	return result
}

// modelStockInfo is an internal type for building the curated stock list.
type modelStockInfo struct {
	Code     string
	Name     string
	Exchange string
	Sector   string
}
