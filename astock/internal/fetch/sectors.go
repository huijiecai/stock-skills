// TargetSectors is the ordered list of target sectors.
var TargetSectors = []string{"PCB", "光模块", "光纤", "液冷", "存储芯片", "半导体", "AI电源", "商业航天", "机器人", "固态电池"}

// ClassifyStock determines which sector a stock belongs to.
// First checks the curated code map, then falls back to keyword matching on name.
func ClassifyStock(code, name string) string {
	for sector, codes := range SectorStockMap {
		for _, c := range codes {
			if c == code {
				return sector
			}
		}
	}
	for _, sector := range TargetSectors {
		keywords := SectorKeywords[sector]
		for _, kw := range keywords {
			if strings.Contains(name, kw) {
				return sector
			}
		}
	}
	return ""
}

// BuildSectorIndex builds a reverse index from stock code to sector name.
func BuildSectorIndex() map[string]string {
	idx := make(map[string]string)
	for sector, codes := range SectorStockMap {
		for _, code := range codes {
			idx[code] = sector
		}
	}
	return idx
}
